-- Dashboard de cliente agregado: preserva o caminho otimizado da 0021 e
-- expande qualquer chave canônica para todos os códigos que a compõem.
CREATE OR REPLACE FUNCTION client_dashboard_summary(p_cod_cliente TEXT, p_ano INT)
RETURNS TABLE (
  periodo TEXT, ano INT, total_faturado NUMERIC, total_unidades NUMERIC,
  total_pedidos BIGINT, total_produtos BIGINT, meses_ativos INT,
  melhor_mes SMALLINT, ultimo_pedido DATE, faturamento_vitalicio NUMERIC,
  pedidos_vitalicios BIGINT, anos_ativos BIGINT
)
LANGUAGE SQL STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
  WITH authorized_owners AS (
    SELECT auth.uid() AS user_id
    UNION SELECT profile.id FROM profiles profile WHERE profile.leader_id = auth.uid()
  ), base AS (
    SELECT
      sales.ano, sales.mes, sales.valor_total, sales.quantidade,
      sales.cod_referencia, sales.data_pedido,
      sales.user_id::TEXT || ':' || COALESCE(sales.data_pedido::TEXT, 'sem-data') || ':' ||
        COALESCE(NULLIF(TRIM(sales.codigo_pedido), ''), NULLIF(TRIM(sales.numero_pedido_talao), ''), NULLIF(TRIM(sales.pedido_cliente_opc), ''), sales.cod_referencia) AS order_key
    FROM sales_rows sales
    JOIN authorized_owners owner ON owner.user_id = sales.user_id
    WHERE sales.cod_cliente IN (SELECT code.cod_cliente FROM resolve_client_codes(p_cod_cliente) code)
  ), vitalicio AS (
    SELECT COALESCE(SUM(base.valor_total), 0) AS faturamento_vitalicio,
      COUNT(DISTINCT base.order_key) AS pedidos_vitalicios,
      COUNT(DISTINCT base.ano) AS anos_ativos,
      MAX(base.data_pedido) AS ultimo_pedido
    FROM base
  ), por_periodo AS (
    SELECT base.ano,
      COALESCE(SUM(base.valor_total), 0) AS total_faturado,
      COALESCE(SUM(base.quantidade), 0) AS total_unidades,
      COUNT(DISTINCT base.order_key) AS total_pedidos,
      COUNT(DISTINCT base.cod_referencia) AS total_produtos,
      COUNT(DISTINCT CASE WHEN base.valor_total > 0 THEN base.mes END) AS meses_ativos
    FROM base WHERE base.ano IN (p_ano, p_ano - 1) GROUP BY base.ano
  ), mes_faturado AS (
    SELECT base.ano, base.mes, COALESCE(SUM(base.valor_total), 0) AS faturado_mes
    FROM base WHERE base.ano IN (p_ano, p_ano - 1) GROUP BY base.ano, base.mes
  ), melhor_mes_por_ano AS (
    SELECT DISTINCT ON (month_row.ano) month_row.ano, month_row.mes AS melhor_mes
    FROM mes_faturado month_row
    ORDER BY month_row.ano, month_row.faturado_mes DESC, month_row.mes
  )
  SELECT CASE WHEN period_row.ano = p_ano THEN 'current' ELSE 'previous' END,
    period_row.ano, period_row.total_faturado, period_row.total_unidades,
    period_row.total_pedidos, period_row.total_produtos,
    COALESCE(period_row.meses_ativos, 0)::INT,
    COALESCE(best_month.melhor_mes, 1)::SMALLINT,
    lifetime.ultimo_pedido, lifetime.faturamento_vitalicio,
    lifetime.pedidos_vitalicios, lifetime.anos_ativos
  FROM por_periodo period_row
  CROSS JOIN vitalicio lifetime
  LEFT JOIN melhor_mes_por_ano best_month ON best_month.ano = period_row.ano
  ORDER BY period_row.ano DESC;
$$;

