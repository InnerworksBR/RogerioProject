-- Compatibilidade para contas que configuraram relatórios pelo usuário de um
-- representante: o item mais recente é copiado para o líder apenas quando ele
-- ainda não possui o mesmo relatório/referência. As linhas antigas permanecem.
WITH representative_config AS (
  SELECT
    profile.leader_id AS account_owner_id,
    config.report_key,
    config.cod_referencia,
    config.categoria,
    config.label,
    config.sort_order,
    config.extra_data,
    config.created_at,
    ROW_NUMBER() OVER (
      PARTITION BY profile.leader_id, config.report_key, config.cod_referencia
      ORDER BY config.created_at DESC, config.id DESC
    ) AS preference
  FROM report_config_items config
  JOIN profiles profile ON profile.id = config.user_id
  WHERE profile.role = 'rep'
    AND profile.leader_id IS NOT NULL
    AND config.cod_referencia IS NOT NULL
)
INSERT INTO report_config_items (
  user_id, report_key, cod_referencia, categoria, label, sort_order, extra_data, created_at
)
SELECT
  account_owner_id, report_key, cod_referencia, categoria, label, sort_order, extra_data, created_at
FROM representative_config
WHERE preference = 1
ON CONFLICT (user_id, report_key, cod_referencia)
  WHERE cod_referencia IS NOT NULL
DO NOTHING;

-- Resolve uma chave canônica. Uma chave legada que já seja membro de grupo
-- também se expande para todos os membros, evitando resultados divergentes.
CREATE OR REPLACE FUNCTION resolve_client_codes(p_client_key TEXT)
RETURNS TABLE (cod_cliente TEXT)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_owner UUID := current_account_owner_id();
  v_group UUID;
BEGIN
  IF p_client_key IS NULL OR TRIM(p_client_key) = '' THEN
    RETURN;
  END IF;

  IF p_client_key ~* '^group:[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$' THEN
    v_group := SUBSTRING(p_client_key FROM 7)::UUID;
  ELSE
    SELECT member.group_id INTO v_group
    FROM client_group_members member
    WHERE member.account_owner_id = v_owner
      AND member.cod_cliente = p_client_key
    LIMIT 1;
  END IF;

  IF v_group IS NOT NULL THEN
    RETURN QUERY
      SELECT member.cod_cliente
      FROM client_group_members member
      WHERE member.account_owner_id = v_owner
        AND member.group_id = v_group
      ORDER BY member.cod_cliente;
  ELSE
    RETURN QUERY SELECT p_client_key;
  END IF;
END;
$$;

REVOKE ALL ON FUNCTION resolve_client_codes(TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION resolve_client_codes(TEXT) TO authenticated;

CREATE OR REPLACE FUNCTION search_raw_clients(p_query TEXT DEFAULT '', p_limit INT DEFAULT 500)
RETURNS TABLE (cod_cliente TEXT, nome_cliente TEXT, group_id UUID, group_name TEXT)
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  WITH authorized_owners AS (
    SELECT auth.uid() AS user_id
    UNION
    SELECT profile.id FROM profiles profile WHERE profile.leader_id = auth.uid()
  ),
  raw AS (
    SELECT sales.cod_cliente, MAX(sales.nome_cliente) AS nome_cliente
    FROM sales_rows sales
    JOIN authorized_owners owner ON owner.user_id = sales.user_id
    WHERE TRIM(p_query) = ''
      OR LOWER(sales.cod_cliente) LIKE '%' || LOWER(TRIM(p_query)) || '%'
      OR LOWER(sales.nome_cliente) LIKE '%' || LOWER(TRIM(p_query)) || '%'
    GROUP BY sales.cod_cliente
  )
  SELECT raw.cod_cliente, raw.nome_cliente, member.group_id, group_row.name
  FROM raw
  LEFT JOIN client_group_members member
    ON member.account_owner_id = current_account_owner_id()
    AND member.cod_cliente = raw.cod_cliente
  LEFT JOIN client_groups group_row ON group_row.id = member.group_id
  ORDER BY raw.nome_cliente, raw.cod_cliente
  LIMIT LEAST(GREATEST(COALESCE(p_limit, 500), 1), 1000);
$$;

CREATE OR REPLACE FUNCTION save_client_group(p_group_id UUID, p_name TEXT, p_codes TEXT[])
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_group_id UUID := p_group_id;
  v_codes TEXT[];
  v_code_count INT;
  v_existing_count INT;
BEGIN
  IF NOT is_current_account_leader() OR current_account_owner_id() <> auth.uid() THEN
    RAISE EXCEPTION 'Leader access required' USING ERRCODE = '42501';
  END IF;
  IF CHAR_LENGTH(TRIM(COALESCE(p_name, ''))) NOT BETWEEN 2 AND 120 THEN
    RAISE EXCEPTION 'Invalid group name' USING ERRCODE = '22023';
  END IF;

  SELECT ARRAY_AGG(code ORDER BY code), COUNT(*)
    INTO v_codes, v_code_count
  FROM (SELECT DISTINCT TRIM(value) AS code FROM UNNEST(COALESCE(p_codes, ARRAY[]::TEXT[])) value WHERE TRIM(value) <> '') normalized;

  IF v_code_count < 2 OR v_code_count > 100 THEN
    RAISE EXCEPTION 'A group must contain between 2 and 100 clients' USING ERRCODE = '22023';
  END IF;

  SELECT COUNT(DISTINCT sales.cod_cliente) INTO v_existing_count
  FROM sales_rows sales
  WHERE sales.cod_cliente = ANY(v_codes)
    AND (
      sales.user_id = auth.uid()
      OR sales.user_id IN (SELECT profile.id FROM profiles profile WHERE profile.leader_id = auth.uid())
    );
  IF v_existing_count <> v_code_count THEN
    RAISE EXCEPTION 'One or more clients are outside the account' USING ERRCODE = '42501';
  END IF;

  IF v_group_id IS NULL THEN
    INSERT INTO client_groups (account_owner_id, name, created_by)
    VALUES (auth.uid(), TRIM(p_name), auth.uid())
    RETURNING id INTO v_group_id;
  ELSE
    UPDATE client_groups
    SET name = TRIM(p_name), updated_at = NOW()
    WHERE id = v_group_id AND account_owner_id = auth.uid();
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Group not found' USING ERRCODE = 'P0002';
    END IF;
    DELETE FROM client_group_members WHERE group_id = v_group_id AND account_owner_id = auth.uid();
  END IF;

  INSERT INTO client_group_members (group_id, account_owner_id, cod_cliente, nome_cliente)
  SELECT
    v_group_id,
    auth.uid(),
    code,
    (
      SELECT MAX(sales.nome_cliente)
      FROM sales_rows sales
      WHERE sales.cod_cliente = code
        AND (
          sales.user_id = auth.uid()
          OR sales.user_id IN (SELECT profile.id FROM profiles profile WHERE profile.leader_id = auth.uid())
        )
    )
  FROM UNNEST(v_codes) code;

  RETURN v_group_id;
END;
$$;

CREATE OR REPLACE FUNCTION delete_client_group(p_group_id UUID)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  IF NOT is_current_account_leader() OR current_account_owner_id() <> auth.uid() THEN
    RAISE EXCEPTION 'Leader access required' USING ERRCODE = '42501';
  END IF;

  DELETE FROM client_groups
  WHERE id = p_group_id AND account_owner_id = auth.uid();
  RETURN FOUND;
END;
$$;

