  WITH authorized_owners AS (
    SELECT auth.uid() AS user_id
    UNION SELECT profile.id FROM profiles profile WHERE profile.leader_id = auth.uid()
  ), scoped AS (
    SELECT sales.cod_referencia, sales.descr_produto, sales.ano,
      sales.valor_total, sales.quantidade, sales.data_pedido,
      sales.user_id::TEXT || ':' || COALESCE(sales.data_pedido::TEXT, 'sem-data') || ':' ||
        COALESCE(NULLIF(TRIM(sales.codigo_pedido), ''), NULLIF(TRIM(sales.numero_pedido_talao), ''), NULLIF(TRIM(sales.pedido_cliente_opc), ''), sales.cod_referencia) AS order_key
