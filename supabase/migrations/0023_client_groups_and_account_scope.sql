    AND (p_descr_hist_financ IS NULL OR s.descr_hist_financ = p_descr_hist_financ)
  GROUP BY s.ano, s.cod_referencia ORDER BY s.cod_referencia;
$$;

CREATE OR REPLACE FUNCTION dashboard_summary(p_ano INT DEFAULT NULL, p_cod_cliente TEXT DEFAULT NULL, p_cod_referencia TEXT DEFAULT NULL, p_semestre INT DEFAULT NULL, p_descr_hist_financ TEXT DEFAULT NULL)
RETURNS TABLE (total_pedidos BIGINT, total_faturado NUMERIC, num_clientes BIGINT, num_produtos BIGINT, total_unidades NUMERIC, data_inicio DATE, data_fim DATE, anos_disponiveis INT[])
LANGUAGE SQL STABLE AS $$
  SELECT
    COUNT(DISTINCT s.codigo_pedido),
    COALESCE(SUM(s.valor_total),0),
    COUNT(DISTINCT COALESCE('group:' || m.group_id::TEXT, s.cod_cliente)),
    COUNT(DISTINCT s.cod_referencia),
    COALESCE(SUM(s.quantidade),0),
    MIN(s.data_pedido), MAX(s.data_pedido),
    ARRAY(SELECT DISTINCT years.ano FROM sales_rows years ORDER BY years.ano)
  FROM sales_rows s
  LEFT JOIN client_group_members m
    ON m.account_owner_id = current_account_owner_id() AND m.cod_cliente = s.cod_cliente
  WHERE (p_ano IS NULL OR s.ano = p_ano)
    AND (p_cod_cliente IS NULL OR s.cod_cliente IN (SELECT code.cod_cliente FROM resolve_client_codes(p_cod_cliente) code))
    AND (p_cod_referencia IS NULL OR s.cod_referencia = p_cod_referencia)
    AND (p_semestre IS NULL OR (p_semestre=1 AND s.mes BETWEEN 1 AND 6) OR (p_semestre=2 AND s.mes BETWEEN 7 AND 12))
    AND (p_descr_hist_financ IS NULL OR s.descr_hist_financ = p_descr_hist_financ);
$$;

CREATE OR REPLACE FUNCTION configured_report_rows(p_report_key TEXT, p_anos INT[], p_cod_cliente TEXT DEFAULT NULL, p_cod_referencia TEXT DEFAULT NULL, p_semestre INT DEFAULT NULL, p_descr_hist_financ TEXT DEFAULT NULL)
RETURNS TABLE (id BIGINT, sort_order INTEGER, cod_referencia TEXT, label TEXT, extra_data JSONB, totals_by_year JSONB)
LANGUAGE SQL STABLE AS $$
  SELECT c.id, c.sort_order, c.cod_referencia, COALESCE(c.label, MAX(s.descr_produto), c.cod_referencia), c.extra_data,
    COALESCE(jsonb_object_agg(s.ano::TEXT, s.qty) FILTER (WHERE s.ano IS NOT NULL), '{}'::JSONB)
  FROM report_config_items c
  LEFT JOIN (
    SELECT sr.cod_referencia, sr.ano, SUM(sr.quantidade) AS qty, MAX(sr.descr_produto) AS descr_produto
    FROM sales_rows sr
    WHERE sr.ano = ANY(p_anos)
      AND (p_cod_cliente IS NULL OR sr.cod_cliente IN (SELECT code.cod_cliente FROM resolve_client_codes(p_cod_cliente) code))
      AND (p_cod_referencia IS NULL OR sr.cod_referencia = p_cod_referencia)
      AND (p_semestre IS NULL OR (p_semestre=1 AND sr.mes BETWEEN 1 AND 6) OR (p_semestre=2 AND sr.mes BETWEEN 7 AND 12))
      AND (p_descr_hist_financ IS NULL OR sr.descr_hist_financ = p_descr_hist_financ)
    GROUP BY sr.cod_referencia, sr.ano
  ) s ON s.cod_referencia = c.cod_referencia
  WHERE c.report_key = p_report_key
  GROUP BY c.id,c.sort_order,c.cod_referencia,c.label,c.extra_data
  ORDER BY c.sort_order,c.cod_referencia;
$$;

