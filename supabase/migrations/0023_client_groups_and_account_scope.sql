CREATE POLICY client_groups_write_leader ON client_groups
  FOR ALL TO authenticated
  USING (account_owner_id = auth.uid() AND is_current_account_leader())
  WITH CHECK (
    account_owner_id = auth.uid()
    AND created_by = auth.uid()
    AND is_current_account_leader()
  );

