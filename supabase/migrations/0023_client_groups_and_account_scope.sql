CREATE TABLE IF NOT EXISTS client_groups (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  account_owner_id UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  name TEXT NOT NULL CHECK (CHAR_LENGTH(TRIM(name)) BETWEEN 2 AND 120),
  created_by UUID NOT NULL REFERENCES profiles(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (id, account_owner_id)
);

CREATE TABLE IF NOT EXISTS client_group_members (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id UUID NOT NULL,
  account_owner_id UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  cod_cliente TEXT NOT NULL CHECK (CHAR_LENGTH(TRIM(cod_cliente)) BETWEEN 1 AND 160),
  nome_cliente TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT client_group_members_group_account_fkey
    FOREIGN KEY (group_id, account_owner_id)
    REFERENCES client_groups(id, account_owner_id)
    ON DELETE CASCADE,
  CONSTRAINT client_group_members_account_code_key
    UNIQUE (account_owner_id, cod_cliente),
  CONSTRAINT client_group_members_group_code_key
    UNIQUE (group_id, cod_cliente)
);

CREATE INDEX IF NOT EXISTS idx_client_groups_account_name
  ON client_groups(account_owner_id, name);
CREATE INDEX IF NOT EXISTS idx_client_group_members_group
  ON client_group_members(group_id, cod_cliente);

