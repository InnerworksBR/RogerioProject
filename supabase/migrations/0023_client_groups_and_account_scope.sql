GRANT EXECUTE ON FUNCTION chat_rep_performance(INT, INT) TO authenticated;

-- Configuração efetiva: a linha do líder é a única lida pela conta.
-- Esta troca fica no fim da migration para reduzir o tempo de retenção do lock
-- forte exigido pelo DDL de políticas. Linhas históricas permanecem preservadas.
DROP POLICY IF EXISTS "saas_config_access" ON report_config_items;
DROP POLICY IF EXISTS "account_config_read" ON report_config_items;
DROP POLICY IF EXISTS "account_config_insert" ON report_config_items;
DROP POLICY IF EXISTS "account_config_update" ON report_config_items;
DROP POLICY IF EXISTS "account_config_delete" ON report_config_items;

CREATE POLICY account_config_read ON report_config_items
  FOR SELECT TO authenticated
  USING (user_id = current_account_owner_id());

CREATE POLICY account_config_insert ON report_config_items
  FOR INSERT TO authenticated
  WITH CHECK (user_id = auth.uid() AND is_current_account_leader());

CREATE POLICY account_config_update ON report_config_items
  FOR UPDATE TO authenticated
  USING (user_id = auth.uid() AND is_current_account_leader())
  WITH CHECK (user_id = auth.uid() AND is_current_account_leader());

CREATE POLICY account_config_delete ON report_config_items
  FOR DELETE TO authenticated
  USING (user_id = auth.uid() AND is_current_account_leader());

