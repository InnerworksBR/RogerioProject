CREATE OR REPLACE FUNCTION account_owner_for_user(p_user_id UUID)
RETURNS UUID
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT COALESCE(
    (SELECT profile.leader_id FROM profiles profile WHERE profile.id = p_user_id),
    p_user_id
  );
$$;

CREATE OR REPLACE FUNCTION current_account_owner_id()
RETURNS UUID
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT account_owner_for_user(auth.uid());
$$;

CREATE OR REPLACE FUNCTION is_current_account_leader()
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT EXISTS (
    SELECT 1 FROM profiles profile
    WHERE profile.id = auth.uid()
      AND profile.role = 'leader'
      AND profile.leader_id IS NULL
  );
$$;

