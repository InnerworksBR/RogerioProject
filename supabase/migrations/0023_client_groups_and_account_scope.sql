-- Catálogo: grupos aparecem uma vez; membros deixam de aparecer isoladamente.
CREATE OR REPLACE FUNCTION search_clients(
  p_query TEXT DEFAULT '',
  p_limit INT DEFAULT 12,
  p_offset INT DEFAULT 0
)
RETURNS TABLE (cod_cliente TEXT, nome_cliente TEXT)
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  WITH authorized_owners AS (
    SELECT auth.uid() AS user_id
    UNION
    SELECT profile.id FROM profiles profile WHERE profile.leader_id = auth.uid()
  ),
  raw_clients AS (
    SELECT sales.cod_cliente, MAX(sales.nome_cliente) AS nome_cliente
    FROM sales_rows sales
    JOIN authorized_owners owner ON owner.user_id = sales.user_id
    GROUP BY sales.cod_cliente
  ),
  normalized AS (
    SELECT
      NULLIF(LOWER(TRIM(p_query)), '') AS query_text,
      NULLIF(REGEXP_REPLACE(LOWER(TRIM(p_query)), '[^a-z0-9]+', '', 'g'), '') AS query_compact,
      NULLIF(REGEXP_REPLACE(TRIM(p_query), '[^0-9]+', '', 'g'), '') AS query_digits
  ),
  options AS (
    SELECT
      'group:' || group_row.id::TEXT AS cod_cliente,
      group_row.name AS nome_cliente,
      group_row.name || ' ' || COALESCE(
        STRING_AGG(DISTINCT member.cod_cliente || ' ' || COALESCE(raw.nome_cliente, ''), ' '),
        ''
      ) AS search_text
    FROM client_groups group_row
    LEFT JOIN client_group_members member
      ON member.account_owner_id = group_row.account_owner_id
      AND member.group_id = group_row.id
    LEFT JOIN raw_clients raw ON raw.cod_cliente = member.cod_cliente
    WHERE group_row.account_owner_id = current_account_owner_id()
    GROUP BY group_row.id, group_row.name

    UNION ALL

    SELECT raw.cod_cliente, raw.nome_cliente, raw.cod_cliente || ' ' || raw.nome_cliente
    FROM raw_clients raw
    WHERE NOT EXISTS (
      SELECT 1 FROM client_group_members member
      WHERE member.account_owner_id = current_account_owner_id()
        AND member.cod_cliente = raw.cod_cliente
    )
  )
  SELECT option.cod_cliente, option.nome_cliente
  FROM options option
  CROSS JOIN normalized query
  WHERE query.query_text IS NULL
    OR LOWER(option.search_text) LIKE '%' || query.query_text || '%'
    OR REGEXP_REPLACE(LOWER(option.search_text), '[^a-z0-9]+', '', 'g') LIKE '%' || query.query_compact || '%'
    OR REGEXP_REPLACE(option.search_text, '[^0-9]+', '', 'g') LIKE '%' || query.query_digits || '%'
  ORDER BY
    CASE
      WHEN LOWER(option.cod_cliente) = query.query_text THEN 0
      WHEN LOWER(option.nome_cliente) = query.query_text THEN 1
      ELSE 2
    END,
    option.nome_cliente,
    option.cod_cliente
  LIMIT LEAST(GREATEST(COALESCE(p_limit, 12), 1), 100)
  OFFSET GREATEST(COALESCE(p_offset, 0), 0);
$$;

REVOKE ALL ON FUNCTION search_clients(TEXT, INT, INT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION search_clients(TEXT, INT, INT) TO authenticated;

CREATE OR REPLACE FUNCTION tabela_dinamica_geral(
  p_ano INT,
  p_cod_cliente TEXT DEFAULT NULL,
  p_cod_referencia TEXT DEFAULT NULL,
  p_semestre INT DEFAULT NULL,
  p_descr_hist_financ TEXT DEFAULT NULL
)
RETURNS TABLE (ano SMALLINT, cod_cliente TEXT, nome_cliente TEXT, apelido TEXT, cod_referencia TEXT, descr_produto TEXT, jan NUMERIC, fev NUMERIC, mar NUMERIC, abr NUMERIC, mai NUMERIC, jun NUMERIC, jul NUMERIC, ago NUMERIC, set_ NUMERIC, out_ NUMERIC, nov NUMERIC, dez NUMERIC, total_ano NUMERIC, total_valor NUMERIC)
LANGUAGE SQL STABLE AS $$
  SELECT
    s.ano,
    COALESCE('group:' || g.id::TEXT, s.cod_cliente),
    COALESCE(g.name, MAX(s.nome_cliente)),
    CASE WHEN g.id IS NULL THEN MAX(s.apelido) ELSE NULL END,
    s.cod_referencia,
    MAX(s.descr_produto),
    SUM(CASE WHEN s.mes=1 THEN s.quantidade ELSE 0 END), SUM(CASE WHEN s.mes=2 THEN s.quantidade ELSE 0 END), SUM(CASE WHEN s.mes=3 THEN s.quantidade ELSE 0 END), SUM(CASE WHEN s.mes=4 THEN s.quantidade ELSE 0 END),
    SUM(CASE WHEN s.mes=5 THEN s.quantidade ELSE 0 END), SUM(CASE WHEN s.mes=6 THEN s.quantidade ELSE 0 END), SUM(CASE WHEN s.mes=7 THEN s.quantidade ELSE 0 END), SUM(CASE WHEN s.mes=8 THEN s.quantidade ELSE 0 END),
    SUM(CASE WHEN s.mes=9 THEN s.quantidade ELSE 0 END), SUM(CASE WHEN s.mes=10 THEN s.quantidade ELSE 0 END), SUM(CASE WHEN s.mes=11 THEN s.quantidade ELSE 0 END), SUM(CASE WHEN s.mes=12 THEN s.quantidade ELSE 0 END),
    SUM(s.quantidade), SUM(s.valor_total)
  FROM sales_rows s
  LEFT JOIN client_group_members m
    ON m.account_owner_id = current_account_owner_id() AND m.cod_cliente = s.cod_cliente
  LEFT JOIN client_groups g ON g.id = m.group_id
  WHERE s.ano = p_ano
    AND (p_cod_cliente IS NULL OR s.cod_cliente IN (SELECT code.cod_cliente FROM resolve_client_codes(p_cod_cliente) code))
    AND (p_cod_referencia IS NULL OR s.cod_referencia = p_cod_referencia)
    AND (p_semestre IS NULL OR (p_semestre=1 AND s.mes BETWEEN 1 AND 6) OR (p_semestre=2 AND s.mes BETWEEN 7 AND 12))
    AND (p_descr_hist_financ IS NULL OR s.descr_hist_financ = p_descr_hist_financ)
  GROUP BY s.ano, COALESCE('group:' || g.id::TEXT, s.cod_cliente), g.id, g.name, s.cod_referencia
  ORDER BY COALESCE(g.name, MAX(s.nome_cliente)), s.cod_referencia;
$$;

CREATE OR REPLACE FUNCTION base_de_compra(p_ano INT, p_cod_cliente TEXT DEFAULT NULL, p_cod_referencia TEXT DEFAULT NULL, p_semestre INT DEFAULT NULL, p_descr_hist_financ TEXT DEFAULT NULL)
RETURNS TABLE (ano SMALLINT, cod_referencia TEXT, descr_produto TEXT, jan NUMERIC, fev NUMERIC, mar NUMERIC, abr NUMERIC, mai NUMERIC, jun NUMERIC, jul NUMERIC, ago NUMERIC, set_ NUMERIC, out_ NUMERIC, nov NUMERIC, dez NUMERIC, total_ano NUMERIC)
LANGUAGE SQL STABLE AS $$
  SELECT s.ano, s.cod_referencia, MAX(s.descr_produto),
    SUM(CASE WHEN s.mes=1 THEN s.quantidade ELSE 0 END), SUM(CASE WHEN s.mes=2 THEN s.quantidade ELSE 0 END), SUM(CASE WHEN s.mes=3 THEN s.quantidade ELSE 0 END), SUM(CASE WHEN s.mes=4 THEN s.quantidade ELSE 0 END),
    SUM(CASE WHEN s.mes=5 THEN s.quantidade ELSE 0 END), SUM(CASE WHEN s.mes=6 THEN s.quantidade ELSE 0 END), SUM(CASE WHEN s.mes=7 THEN s.quantidade ELSE 0 END), SUM(CASE WHEN s.mes=8 THEN s.quantidade ELSE 0 END),
    SUM(CASE WHEN s.mes=9 THEN s.quantidade ELSE 0 END), SUM(CASE WHEN s.mes=10 THEN s.quantidade ELSE 0 END), SUM(CASE WHEN s.mes=11 THEN s.quantidade ELSE 0 END), SUM(CASE WHEN s.mes=12 THEN s.quantidade ELSE 0 END), SUM(s.quantidade)
  FROM sales_rows s
  WHERE s.ano = p_ano
    AND (p_cod_cliente IS NULL OR s.cod_cliente IN (SELECT code.cod_cliente FROM resolve_client_codes(p_cod_cliente) code))
    AND (p_cod_referencia IS NULL OR s.cod_referencia = p_cod_referencia)
