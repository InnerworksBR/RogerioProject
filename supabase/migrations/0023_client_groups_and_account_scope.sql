    WHERE sales.cod_cliente IN (SELECT code.cod_cliente FROM resolve_client_codes(p_cod_cliente) code)
      AND sales.ano IN (p_ano, p_ano - 1)
  ), top_codes AS (
    SELECT scoped.cod_referencia
    FROM scoped
    GROUP BY scoped.cod_referencia
    ORDER BY SUM(scoped.valor_total) DESC
    LIMIT LEAST(GREATEST(COALESCE(p_limit, 50), 1), 100)
  )
